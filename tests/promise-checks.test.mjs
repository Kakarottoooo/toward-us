import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtemp, mkdir, rm } from "node:fs/promises";
import { join, resolve } from "node:path";
import { randomUUID } from "node:crypto";
import express from "express";
import { createFileStore } from "../server/store.mjs";
import { createReminderService } from "../server/reminder-service.mjs";
import { createAssistantRouter } from "../server/assistant-router.mjs";
import { createRelationshipRecord } from "../server/relationship-domain.mjs";
import { askAboutPromise } from "../server/promise-checks.mjs";

const fields = (patch = {}) => ({ title: null, text: null, localDateTime: null, timezone: null, frequency: null, date: null, mood: null, layout: null, spaceId: null, done: null, photoId: null, ...patch });

test("Pinky asks one member privately about their promise, at most daily and weekly, and keeps the answer to them", async (t) => {
  const base = resolve("work"); await mkdir(base, { recursive: true });
  const directory = await mkdtemp(join(base, "promises-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const store = await createFileStore(join(directory, "store.json"));
  const [a, b] = [randomUUID(), randomUUID()];
  for (const id of [a, b]) await store.createUser({ id, email: `${id}@example.invalid`, name: id === a ? "Alex" : "Blair", passwordHash: "test", createdAt: new Date().toISOString() });
  const relationshipId = randomUUID();
  await store.createInvitation({ relationship: { id: relationshipId, status: "pending" }, membership: { relationshipId, userId: a, role: "A" }, invitation: { code: relationshipId, relationshipId, createdByUserId: a, expiresAt: "2099-01-01T00:00:00.000Z" } });
  await store.acceptInvitation(relationshipId, b, new Date().toISOString());
  const created = new Date(Date.now() - 3 * 86_400_000).toISOString();
  const mine = createRelationshipRecord({ relationshipId, userId: a, visibility: "shared", aiAccessScope: "joint", status: "active", description: "Cook together on Wednesdays", ownerType: "member_a", createdAt: created });
  const theirs = createRelationshipRecord({ relationshipId, userId: a, visibility: "shared", aiAccessScope: "joint", status: "active", description: "Text when running late", ownerType: "member_b", createdAt: created });
  await store.createRelationshipRecord("commitments", { ...mine, createdAt: created });
  await store.createRelationshipRecord("commitments", { ...theirs, createdAt: created });
  let seen = null;
  const mediator = { planAssistantTurn: async (context) => { seen = context; return { reply: "That's lovely.", actions: [{ kind: "promise", operation: "create", targetId: mine.id, expectedVersion: null, fields: fields({ done: true, text: "we did it" }), query: null, queryPeriod: "all", occurrence: null }] }; } };
  const app = express(); app.use(express.json());
  app.use((req, _res, next) => { if (req.headers["x-user"]) req.auth = { user: { id: req.headers["x-user"] } }; next(); });
  app.use("/api", createAssistantRouter({ store, mediator, reminderService: createReminderService({ store }) }));
  app.use((error, _req, res, _next) => res.status(error.statusCode || 500).json({ error: error.message }));
  const server = app.listen(0, "127.0.0.1"); await new Promise((r) => server.once("listening", r)); t.after(() => server.close());
  const request = async (path, method = "GET", body, user = a) => { const response = await fetch(`http://127.0.0.1:${server.address().port}/api${path}`, { method, headers: { "x-user": user, "content-type": "application/json" }, ...(body ? { body: JSON.stringify(body) } : {}) }); return response.json(); };
  const session = (await request("/assistant/sessions", "POST", { language: "en", timezone: "UTC" })).session;
  const opened = (await request(`/assistant/sessions/${session.id}?opened=1`)).session;
  assert.match(opened.messages.at(-1).text, /Cook together on Wednesdays/, "asks about the promise this member made");
  assert.equal((await request(`/assistant/sessions/${session.id}?opened=1`)).session.messages.length, 1, "at most one question a day");
  const raw = await store.getRelationshipRecordForUser("privateAgentThreads", session.id, a);
  assert.equal(await askAboutPromise(store, { userId: a, session: raw, now: new Date(Date.now() + 3 * 86_400_000) }), null, "not again within a week");
  assert.ok(await askAboutPromise(store, { userId: a, session: raw, now: new Date(Date.now() + 8 * 86_400_000) }), "again after a week");
  await request(`/assistant/sessions/${session.id}/messages`, "POST", { text: "Yes we cooked!", itemId: randomUUID() });
  assert.deepEqual(seen.openPromises.map((promise) => promise.description), ["Cook together on Wednesdays"], "only promises this member owns");
  assert.equal((await request("/assistant/promises")).promises[mine.id].done, true);
  assert.deepEqual((await request("/assistant/promises", "GET", null, b)).promises, {}, "the partner never sees it");
});
